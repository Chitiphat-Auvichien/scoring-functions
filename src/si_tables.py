_LATEX_SPECIAL = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def _esc(val):
    """LaTeX-escape a single cell for a text column. NaN/None -> empty."""
    if val is None or (isinstance(val, float) and pd.isna(val)):
        return ""
    return "".join(_LATEX_SPECIAL.get(ch, ch) for ch in str(val))


def _fmt(val, nd=3):
    """Numeric cell formatter: fixed `nd` decimal places, NaN/None -> empty."""
    if val is None or (isinstance(val, float) and pd.isna(val)):
        return ""
    try:
        s = f"{float(val):.{nd}f}"
        return s[1:] if s.startswith("-") and float(s) == 0.0 else s  # no "-0.000"
    except (TypeError, ValueError):
        return _esc(val)


def _pack_bond_scores(row, bond_cols, nd=3):
    """Join per-bond `s_AB[A-B]` columns into one 'A-B:val; A-B:val' text
    cell (skips NaN entries) -- mirrors the packed `s_AB` string column
    already used by library_scores.csv."""
    parts = []
    for col in bond_cols:
        val = row[col]
        if pd.isna(val):
            continue
        bond = col.split("[", 1)[1].rstrip("]")
        parts.append(f"{bond}:{_fmt(val, nd)}")
    return "; ".join(parts)


def _write_longtable(rows, headers, col_spec, caption, label, out_path,
                      footnote=None, fontsize="\\small", landscape=False):
    """Write a booktabs-style `longtable` fragment. `rows` is a list of lists
    of already-formatted (escaped/rounded) strings; `headers` are already-
    escaped column headers; `col_spec` is the tabular column spec (e.g.
    'lrrl')."""
    ncol = len(headers)
    lines = ["% AUTO-GENERATED by src/si_tables.py / src/si_geometry_export.py -- do not edit by hand."]
    if landscape:
        lines.append("\\begin{landscape}  % requires \\usepackage{pdflscape}")
    lines.append("\\begingroup")
    lines.append(fontsize)
    lines.append("\\setlength{\\tabcolsep}{4pt}")
    lines.append(f"\\begin{{longtable}}{{{col_spec}}}")
    lines.append(f"\\caption{{{caption}}}\\label{{{label}}} \\\\")
    lines.append("\\toprule")
    header_row = " & ".join(headers) + r" \\"
    lines.append(header_row)
    lines.append("\\midrule")
    lines.append("\\endfirsthead")
    lines.append(f"\\multicolumn{{{ncol}}}{{l}}{{\\tablename\\ \\thetable{{}} -- "
                 "continued from previous page} \\\\")
    lines.append("\\toprule")
    lines.append(header_row)
    lines.append("\\midrule")
    lines.append("\\endhead")
    lines.append("\\midrule")
    lines.append(f"\\multicolumn{{{ncol}}}{{r}}{{continued on next page}} \\\\")
    lines.append("\\endfoot")
    lines.append("\\bottomrule")
    if footnote:
        lines.append(f"\\multicolumn{{{ncol}}}{{p{{0.95\\textwidth}}}}{{\\footnotesize {footnote}}} \\\\")
    lines.append("\\endlastfoot")
    for r in rows:
        lines.append(" & ".join(r) + r" \\")
    lines.append("\\end{longtable}")
    lines.append("\\endgroup")
    if landscape:
        lines.append("\\end{landscape}")
    text = "\n".join(lines) + "\n"

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)
    return out_path


_RAW_DATA_FOOTNOTE = (
    "Full raw score tables (including internal diagnostic columns not shown "
    "here) are available in the public code repository -- see the Data "
    "Availability Statement.")


def _write_column_block_table(mode_names, row_labels, data, caption, label,
                               out_path, footnote=None, fontsize="\\small",
                               landscape=True, modes_per_block=9, midrule_after=None):
    """Write a table with items as COLUMNS -- Table 4's own orientation --
    tiled across multiple fixed-size blocks stacked down the page, for a
    dataset with too many items to fit as columns in one block (36 EMIT
    modes at 9/block here) but too few rows for a longtable-style
    row-per-item layout to be the natural shape (see
    benzene_emit_summary_table). Not a `longtable`: each block is a plain
    `tabular`, since no single block's rows need multi-page continuation;
    `\\captionof{table}` (from the already-loaded `caption` package) gives it
    one shared, properly S-numbered caption/label without a floating `table`
    environment, which would not reliably hold multiple stacked blocks in
    place across a landscape page.

    mode_names : list of str, one per item (column), in order.
    row_labels : list of str, already LaTeX-ready (e.g. "$O[\\mathrm{T_x}]$").
    data : dict {mode_name: [formatted str, ...]}, one list per mode with
        one entry per row_labels, in the same order.
    midrule_after : int, optional -- 0-based row_labels index after which to
        insert an extra `\\midrule` inside each block (Table 4 itself has one
        between its O[...]/Ref.-mode block and its s[...]/Label block).
    """
    blocks = [mode_names[i:i + modes_per_block]
              for i in range(0, len(mode_names), modes_per_block)]

    lines = ["% AUTO-GENERATED by src/si_tables.py -- do not edit by hand."]
    if landscape:
        lines.append("\\begin{landscape}  % requires \\usepackage{pdflscape}")
    lines.append("\\begingroup")
    lines.append(fontsize)
    lines.append("\\setlength{\\tabcolsep}{5pt}")
    lines.append("\\begin{center}")
    lines.append(f"\\captionof{{table}}{{{caption}}}\\label{{{label}}}")
    lines.append("\\end{center}")

    for bi, block_modes in enumerate(blocks):
        if bi > 0:
            lines.append("\\bigskip")
            lines.append(f"\\centerline{{\\textit{{Table~\\ref{{{label}}} (continued).}}}}")
            lines.append("\\smallskip")
        col_spec = "l" + "c" * len(block_modes)
        lines.append("\\begin{center}")
        lines.append(f"\\begin{{tabular}}{{{col_spec}}}")
        lines.append("\\toprule")
        lines.append("Mode & " + " & ".join(_esc(m) for m in block_modes) + r" \\")
        lines.append("\\midrule")
        for ri, rlabel in enumerate(row_labels):
            cells = [data[m][ri] for m in block_modes]
            lines.append(rlabel + " & " + " & ".join(cells) + r" \\")
            if midrule_after is not None and ri == midrule_after:
                lines.append("\\midrule")
        lines.append("\\bottomrule")
        lines.append("\\end{tabular}")
        lines.append("\\end{center}")

    if footnote:
        lines.append("\\par\\smallskip\\noindent\\footnotesize " + footnote + "\\par")
    lines.append("\\endgroup")
    if landscape:
        lines.append("\\end{landscape}")
    text = "\n".join(lines) + "\n"

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)
    return out_path


