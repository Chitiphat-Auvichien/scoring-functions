def benzene_emit_table(data_dir=DEFAULT_DATA_DIR, out_dir=DEFAULT_SI_TABLES_DIR):
    """C6H6_EMIT_full.csv -> tab_benzene_emit_full.tex (tab:benzeneemitscores).
    This is the raw eq:emitproj projection matrix (Tx..Rz + all 30 internal-
    vibration reference-basis components per EMIT mode) rather than the
    classify_all_modes summary in C6H6_EMIT.csv -- 38 columns, wrapped in a
    `landscape` block since it will not fit portrait even at \\tiny."""
    df = pd.read_csv(os.path.join(data_dir, "results", "C6H6_EMIT_full.csv"))
    vib_cols = [c for c in df.columns if c.startswith("Vib ")]

    headers = ["Mode", "Eigenvalue",
               "$s[T_x]$", "$s[T_y]$", "$s[T_z]$",
               "$s[R_x]$", "$s[R_y]$", "$s[R_z]$"] + [
        f"Vib {i}" for i in range(1, len(vib_cols) + 1)]
    col_spec = "lr" + "r" * 6 + "r" * len(vib_cols)

    rows = []
    for _, row in df.iterrows():
        rows.append([
            _esc(row["Mode"]), _fmt(row["Eigenvalue"], 2),
            _fmt(row["Tx"]), _fmt(row["Ty"]), _fmt(row["Tz"]),
            _fmt(row["Rx"]), _fmt(row["Ry"]), _fmt(row["Rz"]),
        ] + [_fmt(row[c]) for c in vib_cols])

    caption = ("Full EMIT-mode $\\to$ normal-mode projection matrix for C$_6$H$_6$ "
               "(Equation~\\ref{eq:emitproj}): projections of each of the 36 EMIT "
               "modes onto the 6 external ($T_x$--$R_z$) and 30 internal-vibration "
               "reference-basis vectors.")
    return _write_longtable(rows, headers, col_spec, caption, "tab:benzeneemitscores",
                             os.path.join(out_dir, "tab_benzene_emit_full.tex"),
                             footnote=_RAW_DATA_FOOTNOTE, fontsize="\\tiny",
                             landscape=True)


# --- (B) Benzene EMIT summary (all 36 modes, Table 4 format) ---------------

# Vib-N (internal 1..30 numbering used throughout this repo's CSVs, in
# ascending-frequency order -- see data/results/C6H6_normal.csv) -> literature
# Shimanouchi reference-mode number,\cite{Shi1972} raw LaTeX math ready to
# drop into a cell verbatim (NOT run through _esc()). Notation matches Table
# 4/tab:emitselected's own "Ref. mode" row exactly: italic Latin "v" (e.g.
# "$v_{13}$"), NOT the Greek "\nu" -- the main text's own LaTeX source uses
# "$v_{13}$", not "$\nu_{13}$", despite both being read aloud as "nu". ONLY
# the pairs independently established either by the main-text Table
# \ref{tab:benzenemixed} footnote (six "medium vibrational score" rows,
# matched by frequency) or by this module's own sanity check against the
# eight EMIT modes already published in Table \ref{tab:emitselected} (see
# si_tables benzene_emit_summary_table() docstring for the check and its one
# flagged discrepancy) are included here. Degenerate pairs (E1u/E2g/E1g, each
# spanning two adjacent Vib-N) share one reference-mode number, matching how
# the manuscript itself treats degenerate modes.
_BENZENE_VIB_TO_NU = {
    6: r"$v_{4}$",
    7: r"$v_{11}$", 8: r"$v_{11}$",
    13: r"$v_{14}$", 14: r"$v_{14}$",
    16: r"$v_{10}$",
    17: r"$v_{17}$", 18: r"$v_{17}$",
    19: r"$v_{9}$",
    21: r"$v_{13}$", 22: r"$v_{13}$",
    23: r"$v_{16}$", 24: r"$v_{16}$",
    26: r"$v_{15}$", 27: r"$v_{15}$",
    28: r"$v_{12}$", 29: r"$v_{12}$",
}


def benzene_emit_summary_table(data_dir=DEFAULT_DATA_DIR, out_dir=DEFAULT_SI_TABLES_DIR):
    """All 36 EMIT modes of C6H6 in the same per-mode format as the main
    text's 8-mode Table \\ref{tab:emitselected} -- tab_benzene_emit_summary.tex
    (tab:benzeneemitsummary).

    Column sourcing, per mode:
      O[Tx..Rz]   <- data/results/C6H6_EMIT.csv "Ocart_Tx".."Ocart_Rz"
                     (src.projection.project_emit_cartesian's raw signed,
                     plain-Cartesian overlap; see the sanity-check note below
                     for why this pathway, not the mass-weighted eq:emitproj
                     one, is the one that reproduces Table 4/tab:emitselected).
      O[vm], Vib N <- data/results/C6H6_EMIT_full_cartesian.csv "Vib 1".."Vib
                     30" (same plain-Cartesian pathway's per-reference-mode
                     detail): the signed value of largest magnitude and its
                     index.
      nu (lit.)   <- _BENZENE_VIB_TO_NU, keyed on that Vib-N index; blank for
                     every Vib-N not in the dict (no fabricated assignments).
      s[Tx..Rz], s[Vs], Label, T/R label
                  <- data/results/C6H6_EMIT.csv "Tx".."Rz" (classify_all_modes'
                     own scores, distinct from the Ocart_* overlap columns
                     above despite the shared "Tx" name), "V_Stretch",
                     "vib_label", "tr_label" (blank -> "-").

    Sanity check performed during development (per the task that added this
    function): for the 8 modes already published in Table
    \\ref{tab:emitselected} (EMIT 34,35,36,18,13,19,16,33), O[Tx..Rz], s[Tx..
    Rz], and |O[vm]| all reproduce the published values to ~0.01 using the
    plain-Cartesian "Ocart_*"/project_emit_cartesian() pathway -- e.g. EMIT
    34's Ocart_Tx=0.876 matches the published O[Tx]=0.88, matching
    IMPLEMENTATION_PLAN.md's own pinned ground truth for that value; EMIT 18's
    Ocart_Rx=-0.680 matches O[Rx]=-0.68 and its top Vib-8 overlap (-0.721)
    matches O[vm]=-0.72 (Ref. mode v11). The mass-weighted eq:emitproj
    pathway (src.projection.project_emit's Theta_tilde, squared into the
    "C2_*" columns) does NOT reproduce these numbers (e.g. its unsquared
    signed value for EMIT 18's Rx-overlap comes out -0.357, not -0.68) --
    expected, since Table \\ref{tab:emitselected}'s own caption states it
    projects onto "Cartesian normal coordinates", i.e. the unweighted
    pathway. This function therefore deliberately joins against
    Ocart_*/EMIT_full_cartesian.csv (already produced by the existing
    project_emit_cartesian() call in main.run_projection_pipeline -- no new
    projection logic was needed), so the SI table's 8 previously-published
    rows stay numerically identical to the main text.
    NOTE (flagged, not fixed here): JCC_SI_main.tex si:projection currently
    frames the mass-weighted pathway as primary and the Cartesian one as "a
    diagnostic point of comparison ... not used as an alternative to
    Equation (eq:emitproj) in any of the results reported in the main text"
    -- that description is now stale, since Table 4/tab:emitselected's O[...]
    values ARE the Cartesian pathway's output. Left for lead-author to
    reconcile the prose; not touched by this function.
    One discrepancy remains unresolved and is NOT papered over: EMIT 19's
    published Ref. mode is v13, but v13 is independently pinned (via
    EMIT 34/35 and the tab:benzenemixed footnote) to Vib 21/22 (E1u, 1532.85
    cm^-1) -- EMIT 19 actually has ~0 overlap with those two normal modes.
    EMIT 19's true largest-magnitude overlap is Vib 20 (A2g, 1435.48 cm^-1,
    value 0.743, matching the published O[vm]=0.74 in magnitude), which is
    symmetry-consistent (Rz transforms as A2g in D6h) but has no established
    literature nu-number in this study's data -- likely a labeling
    transcription slip in the main text rather than a data-regeneration
    issue, since every one of EMIT 19's other published numbers (O[Rz]=0.65,
    s[Rz]=0.33, etc.) matches exactly. _BENZENE_VIB_TO_NU is left without a
    Vib-20 entry rather than propagating that label, so this row's "nu (lit.)"
    cell comes out blank automatically -- consistent with the "no fabricated
    assignments" rule below.
    """
    df = pd.read_csv(os.path.join(data_dir, "results", "C6H6_EMIT.csv"))
    df_full = pd.read_csv(os.path.join(data_dir, "results", "C6H6_EMIT_full_cartesian.csv"))
    vib_cols = [c for c in df_full.columns if c.startswith("Vib ")]
    full_by_mode = {row["Mode"]: row for _, row in df_full.iterrows()}

    # T_x/R_x/V_S set in \mathrm{} (upright, per the main text's own
    # "$O[\mathrm{T_x}]$"/"$s[\mathrm{T_x}]$"), so they no longer render in
    # math-italic the way a bare "$o[T_x]$" would. Overlap notation uses
    # lowercase "o" here (not Table 4's own capital "O") -- an intentional
    # departure from Table 4, per explicit request. "Ref. mode" is Table 4's
    # own row (literature Shimanouchi numbering, italic Latin "v" per
    # _BENZENE_VIB_TO_NU above); the internal Vib-N index used to find it
    # (best_col below) is not itself shown as its own row here.
    row_labels = ["Eigenvalue",
                  "$o[\\mathrm{T_x}]$", "$o[\\mathrm{T_y}]$", "$o[\\mathrm{T_z}]$",
                  "$o[\\mathrm{R_x}]$", "$o[\\mathrm{R_y}]$", "$o[\\mathrm{R_z}]$", "$o[v_m]$",
                  "Ref. mode\\cite{Shi1972}", "\\%$\\nu$",
                  "$s[\\mathrm{T_x}]$", "$s[\\mathrm{T_y}]$", "$s[\\mathrm{T_z}]$",
                  "$s[\\mathrm{R_x}]$", "$s[\\mathrm{R_y}]$", "$s[\\mathrm{R_z}]$", "$s[\\mathrm{V_S}]$",
                  "Label", "T/R label"]
    # Index (0-based) of the last row before the s[...] block starts, for the
    # extra \midrule Table 4 itself has between its o[...]/Ref.-mode block
    # and its s[...]/Label/T-R-label block.
    _MIDRULE_AFTER = 9

    # %nu: this study's own real PED analysis (VEDA4, via ped/merge_ped_scores.py
    # -- see JCC_SI_main.tex si:ped), already merged into C6H6_normal.csv's
    # "PED_Stretch_pct" column and keyed on the same "Vib N" identifier as
    # best_col below -- no re-derivation or fresh frequency-matching needed.
    # Every one of benzene's 30 normal modes has a PED row (unlike the sparse
    # literature nu-numbering above), so this is never blank. Values can
    # exceed 100 (e.g. 108) -- expected for this redundant-coordinate PED set,
    # not a bug (see merge_ped_scores.py's module docstring).
    df_normal = pd.read_csv(os.path.join(data_dir, "results", "C6H6_normal.csv"))
    pednu_by_vib = dict(zip(df_normal["Mode"], df_normal["PED_Stretch_pct"]))

    mode_names = []
    data = {}
    for _, row in df.iterrows():
        mode = row["Mode"]
        full_row = full_by_mode[mode]
        vib_vals = full_row[vib_cols].astype(float)
        best_col = vib_vals.abs().idxmax()
        best_val = vib_vals[best_col]
        vib_n = int(best_col.split(" ")[1])
        nu_lit = _BENZENE_VIB_TO_NU.get(vib_n, "")
        pednu_cell = _fmt(pednu_by_vib.get(best_col), 0)

        tr_label = row["tr_label"]
        tr_cell = "-" if pd.isna(tr_label) or str(tr_label).strip() == "" else _esc(tr_label)

        mode_names.append(mode)
        data[mode] = [
            _fmt(row["Eigenvalue"], 2),
            _fmt(row["Ocart_Tx"]), _fmt(row["Ocart_Ty"]), _fmt(row["Ocart_Tz"]),
            _fmt(row["Ocart_Rx"]), _fmt(row["Ocart_Ry"]), _fmt(row["Ocart_Rz"]),
            _fmt(best_val), nu_lit, pednu_cell,
            _fmt(row["Tx"]), _fmt(row["Ty"]), _fmt(row["Tz"]),
            _fmt(row["Rx"]), _fmt(row["Ry"]), _fmt(row["Rz"]), _fmt(row["V_Stretch"]),
            _esc(row["vib_label"]), tr_cell,
        ]

    footnote = (
        "$o$ denotes an overlap from each type of normal modes, including "
        "translation [T], rotation [R], and the highest-overlapped "
        "vibrational mode(s) [$v_m$]. Blank Ref.-mode cells are modes "
        "without a published Shimanouchi assignment in this study. "
        "\\%$\\nu$ is the real VEDA4 PED-derived total stretching "
        "contribution (Section~\\ref{si:ped}) of the matched Vib-$N$ normal "
        "mode; values above 100 reflect this molecule's redundant internal- "
        "coordinate set and are not an error. "
        + _RAW_DATA_FOOTNOTE)
    caption = ("Full listing of all 36 EMIT modes of C$_6$H$_6$ (benzene), tiled in "
               "the same per-mode-as-column format as the main text's 8-mode Table~4 "
               "(\\texttt{tab:emitselected}), extended here to the complete EMIT "
               "eigenbasis.")
    return _write_column_block_table(mode_names, row_labels, data, caption,
                                      "tab:benzeneemitsummary",
                                      os.path.join(out_dir, "tab_benzene_emit_summary.tex"),
                                      footnote=footnote, fontsize="\\footnotesize",
                                      landscape=True, modes_per_block=12,
                                      midrule_after=_MIDRULE_AFTER)


def transferability_misclassified_table(data_dir=DEFAULT_DATA_DIR, out_dir=DEFAULT_SI_TABLES_DIR):
    """transferability_confusion_misclassified.csv -> tab_transferability_misclassified.tex
    (tab:transfermisclassified). Full mode-by-mode listing of the 17 modes
    off the diagonal of Figure~\\ref{fig:transferability_confusion}'s S/B
    confusion matrix, with the literature description and source tag that
    justify the reference label. `ref` values (e.g. "Lip1955") are NOT yet
    entries in MolecularMotion.bib -- bibtex confirmed they're undefined --
    so they're emitted as escaped plain text, not `\\cite{}`, to avoid an
    undefined-citation warning and fabricated bibliography entries. Promote
    to `\\cite{}` once real entries exist for these keys."""
    df = pd.read_csv(os.path.join(data_dir, "results",
                                   "transferability_confusion_misclassified.csv"))

    headers = ["Molecule", "Mode", "Freq (cm$^{-1}$)", "Irrep", "$s[V_S]$",
               "Ref. category", "Predicted", "Description", "Ref."]
    col_spec = "llrlrllll"

    rows = []
    for _, row in df.iterrows():
        rows.append([
            _esc(row["molecule"]), _esc(row["mode_index"]),
            _fmt(row["freq"], 2), _esc(row["irrep"]), _fmt(row["V_Stretch"]),
            _esc(row["ref_category"]), _esc(row["predicted_label"]),
            _esc(row["description"]), _esc(row["ref"]),
        ])

    caption = (f"Mode-by-mode listing of the {len(df)} modes misclassified against "
               "literature reference labels in the 18-molecule transferability test "
               "set (off-diagonal entries of the main text's Figure~6, "
               "\\texttt{fig:transferability\\_confusion}, stretch/bend confusion "
               "matrix), with the literature description and source justifying each "
               "reference label.")
    return _write_longtable(rows, headers, col_spec, caption, "tab:transfermisclassified",
                             os.path.join(out_dir, "tab_transferability_misclassified.tex"),
                             footnote=_RAW_DATA_FOOTNOTE)


